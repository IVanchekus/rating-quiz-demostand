def clarify_questions():
    changed = 0
    with SessionLocal.begin() as session:
        for question in session.scalars(select(Question).with_for_update()):
            text = REPLACEMENTS.get(question.text, question.text)
            if question.company == "sensory_hub" and "Sensory Hub" not in text:
                text = text.rstrip("?") + " (компания Sensory Hub)" + ("?" if text.endswith("?") else "")
            if text.startswith("Какая компания группы "):
                text = text.replace("Какая компания группы ", "Какая компания группы «Питерский мостик» ", 1)
            if question.text != text:
                question.text = text
                changed += 1
    print(f"Updated {changed} question texts in place; options and answers preserved.")


if __name__ == "__main__":
    clarify_questions()
